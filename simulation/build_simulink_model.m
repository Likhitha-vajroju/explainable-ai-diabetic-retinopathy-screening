% Build a daily-step Simulink fluid-queue approximation for resource planning.
% Requires MATLAB, Simulink, and MATLAB Function block support.

scriptPath = mfilename('fullpath');
simulationDirectory = fileparts(scriptPath);
scenarioPath = getenv('DR_SIMULATION_SCENARIO');
if isempty(scenarioPath)
    scenarioPath = fullfile(simulationDirectory, 'scenario_100k.json');
end
scenario = jsondecode(fileread(scenarioPath));
modelName = 'rural_dr_telemedicine_resource_allocation';

if isempty(scenario.daily_arrival_rate)
    dailyArrivalRate = scenario.annual_patient_volume / scenario.simulation_days;
else
    dailyArrivalRate = scenario.daily_arrival_rate;
end
operatingHours = scenario.operating_hours_per_day;
acquisitionRate = scenario.image_acquisition_rate_per_hour;
qualityTime = scenario.image_quality_assessment_time_seconds;
aiTime = scenario.ai_processing_time_seconds;
imageSizeMB = scenario.image_transmission_size_mb;
bandwidthMbps = scenario.available_bandwidth_mbps;
ophthalmologists = scenario.number_of_ophthalmologists;
reviewMinutes = scenario.review_time_per_case_minutes;
processingCapacity = scenario.processing_capacity;
referableFraction = scenario.referable_fraction;
ungradableFraction = scenario.ungradable_fraction;

assignin('base', 'dailyArrivalRate', dailyArrivalRate);
assignin('base', 'operatingHours', operatingHours);
assignin('base', 'acquisitionRate', acquisitionRate);
assignin('base', 'qualityTime', qualityTime);
assignin('base', 'aiTime', aiTime);
assignin('base', 'imageSizeMB', imageSizeMB);
assignin('base', 'bandwidthMbps', bandwidthMbps);
assignin('base', 'ophthalmologists', ophthalmologists);
assignin('base', 'reviewMinutes', reviewMinutes);
assignin('base', 'processingCapacity', processingCapacity);
assignin('base', 'referableFraction', referableFraction);
assignin('base', 'ungradableFraction', ungradableFraction);

if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
new_system(modelName);
open_system(modelName);
set_param(modelName, ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', '1', ...
    'StopTime', num2str(scenario.simulation_days - 1), ...
    'SaveOutput', 'on');

inputNames = { ...
    'dailyArrivalRate', 'operatingHours', 'acquisitionRate', 'qualityTime', ...
    'aiTime', 'imageSizeMB', 'bandwidthMbps', 'ophthalmologists', ...
    'reviewMinutes', 'processingCapacity', 'referableFraction', ...
    'ungradableFraction'};
functionBlock = [modelName '/Daily resource-allocation model'];
add_block('simulink/User-Defined Functions/MATLAB Function', functionBlock, ...
    'Position', [470 100 750 330]);
for inputIndex = 1:numel(inputNames)
    source = sprintf('%s/Parameter %02d', modelName, inputIndex);
    y = 80 + (inputIndex - 1) * 42;
    add_block('simulink/Sources/Constant', source, ...
        'Value', inputNames{inputIndex}, ...
        'SampleTime', '1', ...
        'Position', [40 y 190 y + 24]);
end

stateflowRoot = sfroot;
chart = stateflowRoot.find('-isa', 'Stateflow.EMChart', 'Path', functionBlock);
chart.Script = sprintf([ ...
    'function [arrivalsOut, completedOut, referralsOut, reviewsOut, ' ...
    'queueTotalOut, estimatedQueueWaitHoursOut] = daily_step(' ...
    'dailyArrivalRate, operatingHours, acquisitionRate, qualityTime, aiTime, ' ...
    'imageSizeMB, bandwidthMbps, ophthalmologists, reviewMinutes, ' ...
    'processingCapacity, referableFraction, ungradableFraction)\n' ...
    'persistent q cumulativeArrivals cumulativeCompleted cumulativeReferrals ' ...
    'cumulativeReviews\n' ...
    'if isempty(q)\n' ...
    '    q = zeros(1, 5);\n' ...
    '    cumulativeArrivals = 0;\n' ...
    '    cumulativeCompleted = 0;\n' ...
    '    cumulativeReferrals = 0;\n' ...
    '    cumulativeReviews = 0;\n' ...
    'end\n' ...
    'arrival = dailyArrivalRate;\n' ...
    'acquisitionCap = acquisitionRate * operatingHours;\n' ...
    'qualityCap = operatingHours * 3600 / qualityTime;\n' ...
    'aiCap = processingCapacity * operatingHours * 3600 / aiTime;\n' ...
    'transmissionCap = bandwidthMbps * 1e6 * operatingHours * 3600 / ' ...
    '(imageSizeMB * 1e6 * 8);\n' ...
    'reviewCap = ophthalmologists * operatingHours * 60 / reviewMinutes;\n' ...
    'acquired = min(q(1) + arrival, acquisitionCap);\n' ...
    'qualityAssessed = min(q(2) + acquired, qualityCap);\n' ...
    'gradable = qualityAssessed * (1 - ungradableFraction);\n' ...
    'aiProcessed = min(q(3) + gradable, aiCap);\n' ...
    'referrals = aiProcessed * referableFraction;\n' ...
    'nonReferable = aiProcessed - referrals;\n' ...
    'transmitted = min(q(4) + referrals, transmissionCap);\n' ...
    'reviewed = min(q(5) + transmitted, reviewCap);\n' ...
    'ungradable = qualityAssessed - gradable;\n' ...
    'q(1) = q(1) + arrival - acquired;\n' ...
    'q(2) = q(2) + acquired - qualityAssessed;\n' ...
    'q(3) = q(3) + gradable - aiProcessed;\n' ...
    'q(4) = q(4) + referrals - transmitted;\n' ...
    'q(5) = q(5) + transmitted - reviewed;\n' ...
    'cumulativeArrivals = cumulativeArrivals + arrival;\n' ...
    'cumulativeCompleted = cumulativeCompleted + nonReferable + ' ...
    'ungradable + reviewed;\n' ...
    'cumulativeReferrals = cumulativeReferrals + referrals;\n' ...
    'cumulativeReviews = cumulativeReviews + reviewed;\n' ...
    'arrivalsOut = cumulativeArrivals;\n' ...
    'completedOut = cumulativeCompleted;\n' ...
    'referralsOut = cumulativeReferrals;\n' ...
    'reviewsOut = cumulativeReviews;\n' ...
    'queueTotalOut = sum(q);\n' ...
    'queueDays = q(1) / acquisitionCap + q(2) / qualityCap + ' ...
    'q(3) / aiCap + q(4) / transmissionCap + q(5) / reviewCap;\n' ...
    'estimatedQueueWaitHoursOut = queueDays * 24;\n' ...
    'end']);
set_param(modelName, 'SimulationCommand', 'update');
for inputIndex = 1:numel(inputNames)
    add_line(modelName, sprintf('Parameter %02d/1', inputIndex), ...
        sprintf('Daily resource-allocation model/%d', inputIndex), ...
        'autorouting', 'on');
end

outputNames = { ...
    'cumulativeArrivals', 'cumulativeFinalOutcomes', ...
    'cumulativeReferableCases', 'cumulativeOphthalmologistReviews', ...
    'totalQueuedCases', 'estimatedQueueWaitHours'};
for outputIndex = 1:numel(outputNames)
    sink = sprintf('%s/%s', modelName, outputNames{outputIndex});
    y = 100 + (outputIndex - 1) * 65;
    add_block('simulink/Sinks/To Workspace', sink, ...
        'VariableName', outputNames{outputIndex}, ...
        'SaveFormat', 'Timeseries', ...
        'Position', [900 y 1080 y + 30]);
    add_line(modelName, sprintf('Daily resource-allocation model/%d', outputIndex), ...
        sprintf('%s/1', outputNames{outputIndex}), ...
        'autorouting', 'on');
end

annotation = Simulink.Annotation(modelName, sprintf([ ...
    'Rural PHC -> fundus acquisition -> image-quality assessment -> AI screening\n' ...
    '-> referable-case routing -> network transmission -> ophthalmologist review\n' ...
    '-> final review outcome\n\n' ...
    'Deterministic daily fluid queues. Change scenario_100k.json parameters and ' ...
    'rerun this script to compare resource configurations.\n' ...
    'Planning model only; not clinical validation or a real-world capacity claim.']));
annotation.Position = [40 630 860 710];

save_system(modelName, fullfile(simulationDirectory, [modelName '.slx']));
disp(['Saved Simulink model: ' fullfile(simulationDirectory, [modelName '.slx'])]);
