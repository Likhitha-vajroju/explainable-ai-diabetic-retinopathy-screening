"""Train the five-class DR transfer-learning model."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Sequence

from src.dr_classification.classifier import ClassificationConfig
from src.dr_classification.training import train_model


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Train an experimental five-level DR image classifier."
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=Path("src/dr_classification/config.json"),
        help="JSON model/training configuration.",
    )
    parser.add_argument(
        "--dataset-root",
        type=Path,
        default=Path("data/aptos-20152019-preprocessed"),
    )
    parser.add_argument(
        "--split-csv",
        type=Path,
        default=Path("data/metadata/split_metadata.csv"),
        help="Generated by src.preprocessing.dataset_cli.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("models/checkpoints/dr_resnet18"),
    )
    args = parser.parse_args(argv)
    if not args.config.is_file():
        parser.error(f"Configuration file does not exist: {args.config}")
    if not args.split_csv.is_file():
        parser.error(
            f"Split CSV does not exist: {args.split_csv}. Run "
            "src.preprocessing.dataset_cli first."
        )
    config = ClassificationConfig.from_json(args.config)
    outputs = train_model(
        args.dataset_root, args.split_csv, args.output_dir, config
    )
    print(f"Best checkpoint: {outputs['checkpoint']}")
    print(f"Training history: {outputs['history']}")
    print(f"Training curves: {outputs['curves']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
